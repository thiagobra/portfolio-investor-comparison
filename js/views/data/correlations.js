/**
 * @module   views/data/correlations
 * @purpose  Correlations & volatility editor — two stacked raw-markdown editors,
 *           plus a simple CSV import that overwrites the Asset Class Volatility
 *           rows (label,value pairs — the Damodaran annual-updates export).
 * @exports  mount(root)
 * @reads    @js/import/csv-tokenize.js
 * @usedby   @js/router.js
 */

import { mountTextEditor } from './text-editor.js';
import { tokenizeCSV } from '../../import/csv-tokenize.js';
import { showToast } from '../../toast.js';

const FRENCH_URL = 'https://mba.tuck.dartmouth.edu/pages/faculty/ken.french/data_library.html';
const DAMODARAN_URL = 'https://pages.stern.nyu.edu/~adamodar/New_Home_Page/data.html';

function rewriteAssetClassRows(content, values) {
  const lines = content.split('\n');
  let inAssetTable = false;
  return lines.map((line) => {
    if (/^##\s+Asset Class/.test(line)) { inAssetTable = true; return line; }
    if (/^##\s+/.test(line) && !/Asset Class/.test(line)) { inAssetTable = false; return line; }
    if (!inAssetTable || !line.trim().startsWith('|')) return line;
    const cells = line.slice(1, line.endsWith('|') ? -1 : undefined).split('|').map((c) => c.trim());
    const label = cells[0];
    if (!values.has(label)) return line; // header/divider/unmatched rows stay byte-identical
    cells[cells.length - 1] = String(values.get(label));
    return `| ${cells.join(' | ')} |`;
  }).join('\n');
}

async function importDamodaranCsv(file) {
  const text = await file.text();
  const rows = tokenizeCSV(text).filter((r) => r.length >= 2 && r[0].trim());
  const values = new Map(rows.slice(1).map(([label, value]) => [label.trim(), parseFloat(value)]).filter(([, v]) => !Number.isNaN(v)));
  if (values.size === 0) {
    showToast('No usable rows found — expected "Asset Class,Volatility %" columns', 'error');
    return;
  }

  const res = await fetch('/api/files?path=' + encodeURIComponent('data/volatility.md'));
  const { content } = await res.json();
  const updated = rewriteAssetClassRows(content, values);

  const putRes = await fetch('/api/files', {
    method: 'PUT',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ path: 'data/volatility.md', content: updated }),
  });
  const result = await putRes.json();
  showToast(result.saved ? `✅ Applied ${values.size} asset-class row(s)` : `❌ ${result.error ?? 'save failed'}`, result.saved ? 'info' : 'error');
  return result.saved;
}

export async function mount(root) {
  root.innerHTML = `
    <div id="correlations-editor"></div>
    <div id="volatility-editor"></div>
    <section class="section">
      <div class="card">
        <label for="damodaran-file">Import Damodaran asset-class volatility (CSV: Asset Class,Volatility %)</label>
        <input type="file" id="damodaran-file" accept=".csv">
      </div>
    </section>
  `;

  const mountVolatility = () => mountTextEditor(root.querySelector('#volatility-editor'), {
    path: 'data/volatility.md',
    title: 'Volatility',
    hint: 'Annualised volatility per sector/region/asset-class.',
    sources: [
      { label: 'Ken French Data Library', url: FRENCH_URL },
      { label: 'Damodaran (NYU Stern)', url: DAMODARAN_URL },
    ],
  });

  await Promise.all([
    mountTextEditor(root.querySelector('#correlations-editor'), {
      path: 'data/correlations.md',
      title: 'Correlations',
      hint: 'Sector/region/asset-class correlation matrices, feeding Risk & Diversification\'s volatility figure. Regenerated by tools/build_reference_data.py, or hand-edit here for a quick tweak.',
      sources: [
        { label: 'Ken French Data Library', url: FRENCH_URL },
        { label: 'Damodaran (NYU Stern)', url: DAMODARAN_URL },
      ],
    }),
    mountVolatility(),
  ]);

  root.querySelector('#damodaran-file').addEventListener('change', async (e) => {
    const file = e.target.files[0];
    e.target.value = ''; // allow re-importing the same file
    // Re-mount so the editor shows the imported rows — a stale textarea + Save would overwrite them.
    if (file && await importDamodaranCsv(file)) await mountVolatility();
  });
}
